@dataclass(frozen=True)
class Glyph:
    width: int
    px: tuple[tuple[int, int], ...]


class Font:
    def __init__(self, name: str, glyphs: dict, marks: dict, cap: int, gap: int, ascent: int = 2, tracking: int = 1):
        self.name = name
        self.cap = cap
        self.gap = gap
        self.ascent = ascent
        self.tracking = tracking
        self._glyphs = glyphs
        self._marks = marks
        self._cache: dict[str, Glyph] = {}
        self.missing: set[str] = set()

    def line_height(self, text: str = "") -> int:
        """Cap + gap, plus room for accents when the text carries any above the cap."""
        marks = any(ch in ACCENTED and ACCENTED[ch][1] != "cedilla" for ch in self.normalize(text))
        return self.cap + self.gap + (self.ascent if marks else 0)

    def normalize(self, text) -> str:
        return "".join(NORMALIZE.get(ch, ch) for ch in str(text)).upper()

    def glyph(self, ch: str) -> Glyph:
        g = self._cache.get(ch)
        if g is None:
            g = self._cache[ch] = self._build(ch)
        return g

    def _build(self, ch: str) -> Glyph:
        base, mark = ACCENTED.get(ch, (ch, None))
        spec = self._glyphs.get(base)
        if spec is None:
            self.missing.add(ch)
            spec = self._glyphs["?"]
        dy, rows = spec if isinstance(spec, tuple) else (0, spec)
        rows = rows.split("/")
        width = max(len(r) for r in rows)
        px = [(x, dy + y) for y, r in enumerate(rows) for x, c in enumerate(r) if c == "#"]
        if mark:
            mrows, nudge = self._marks[mark]
            mrows = mrows.split("/")
            ox = (width - max(len(r) for r in mrows)) // 2 + nudge
            oy = self.cap if mark == "cedilla" else -self.ascent
            px += [(ox + x, oy + y) for y, r in enumerate(mrows) for x, c in enumerate(r) if c == "#"]
        return Glyph(width, tuple(px))

    def advance(self, norm: str, scale: int = 1) -> int:
        """Pen advance for already-normalised text, including trailing tracking."""
        return sum(self.glyph(ch).width + self.tracking for ch in norm) * scale

    def measure(self, text, scale: int = 1) -> int:
        norm = self.normalize(text)
        return max(0, self.advance(norm) - self.tracking) * scale if norm else 0

    def ink_rows(self, norm: str) -> tuple[int, int]:
        """Top and bottom (exclusive) rows of ink relative to the cap top, at least the cap itself."""
        ys = [y for ch in norm for _, y in self.glyph(ch).px]
        return min([0, *ys]), max([self.cap - 1, *ys]) + 1

    def wrap(self, text, width: int, scale: int = 1) -> list[str]:
        lines: list[str] = []
        for para in str(text).split("\n"):
            line = ""
            for word in para.split():
                candidate = f"{line} {word}" if line else word
                if line and self.measure(candidate, scale) > width:
                    lines.append(line)
                    line = word
                else:
                    line = candidate
            lines.append(line)
        return lines


